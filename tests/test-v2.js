/* Reproducible SUBTERRA v2 deterministic acceptance tests; no external packages. */
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict"),path=require("node:path");
const root=path.resolve(__dirname,"..");
const sandbox={window:{},console,Date,Math};
vm.runInNewContext(fs.readFileSync(path.join(root,"v2-engine.js"),"utf8"),sandbox);
const E=sandbox.window.SubterraV2;
assert.equal(E.selfTest().initial,14);
assert.equal(E.selfTest().full,100);
const catalog=JSON.parse(fs.readFileSync(path.join(root,"data/field-catalog-v2.json"),"utf8"));
assert.equal(catalog.count,430);
assert.equal(catalog.fields.length,430);
assert.equal(new Set(catalog.fields.map(x=>x.id)).size,430);
assert.equal(catalog.fields.filter(x=>x.id.startsWith("OPN-")).length,52);
const web=fs.readFileSync(path.join(root,"index.html"),"utf8");
assert.match(web,/v2-engine\.js/);assert.match(web,/v2-app\.js/);
assert.doesNotMatch(web,/pipe56|app\.js\?v=0\.16/i);
const config={name:"T",crs:"LOCAL_PROJECT_METRES",verticalDatum:"SITE_BM",targetXY:.03,targetZ:.025};
let p=E.project(config);
p=E.addManhole(p,{id:"A",x:0,y:0,z:130,sigmaXY:.02,sigmaZ:.01});
p=E.addManhole(p,{id:"B",x:100,y:0,z:129,sigmaXY:.02,sigmaZ:.01});
p=E.setPair(p,"A","B");
assert.equal(E.assess(p).score,null,"No route before total-station inventory is signed off");
p=E.setSurfaceSurveyComplete(p,true);
const initial=E.assess(p);
assert.equal(initial.score,14);
assert.equal(initial.route.gradePercent,null,"Cover Z must not become pipe invert Z");
assert.equal(initial.route.hiddenAlignmentUnquantified,true);
p=E.nextRound(p);
assert.equal(p.rounds[0].id,"ROUND-00");
let copy=JSON.stringify(p.rounds[0]);
p=E.addOpening(p,"A",{id:"OUT",role:"OUTLET"});
p=E.addOpening(p,"B",{id:"IN",role:"INLET"});
p=E.addPoint(p,{manholeId:"A",openingId:"OUT",kind:"OPENING_CENTER",x:.5,y:0,z:125,method:"SURVEY_PEN_SIMULATED",sigmaXY:.015,sigmaZ:.015});
p=E.addPoint(p,{manholeId:"B",openingId:"IN",kind:"OPENING_CENTER",x:99.5,y:0,z:124,method:"SURVEY_PEN_SIMULATED",sigmaXY:.015,sigmaZ:.015});
const withPorts=E.assess(p);
assert.ok(withPorts.score>initial.score);
assert.equal(withPorts.route.gradePercent,null);
p=E.addPoint(p,{manholeId:"A",openingId:"OUT",kind:"PIPE_INVERT",x:.5,y:0,z:125,method:"SURVEY_PEN_SIMULATED",sigmaXY:.015,sigmaZ:.015});
p=E.addPoint(p,{manholeId:"B",openingId:"IN",kind:"PIPE_INVERT",x:99.5,y:0,z:124,method:"SURVEY_PEN_SIMULATED",sigmaXY:.015,sigmaZ:.015});
assert.ok(E.assess(p).route.gradePercent>0);
assert.equal(JSON.stringify(p.rounds[0]),copy,"Frozen first round must remain unchanged");
const goodScore=E.assess(p).score;
p=E.addPoint(p,{manholeId:"B",openingId:"IN",kind:"PIPE_INVERT",x:99.5,y:0,z:126,method:"SURVEY_PEN_SIMULATED",sigmaXY:.015,sigmaZ:.015});
assert.equal(E.assess(p).status,"CONFLICT");
assert.ok(E.assess(p).score<goodScore);
p=E.accept(p,"Preliminary alignment accepted with unresolved risk");
assert.equal(p.accepted.status,"USER_ACCEPTED_WITH_UNRESOLVED_RISK");
const reject=E.project(config);
assert.throws(()=>E.addManhole(reject,{id:"A",x:2,y:3,z:4,sigmaXY:-1,sigmaZ:.02}));
console.log("SUBTERRA v2 QA passed: full 430-field catalog; 14/100 initial; unknown pipe Z; independent 100/100 synthetic case; rounds immutable; conflict lowers score; user acceptance.");
